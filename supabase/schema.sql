CREATE OR REPLACE FUNCTION public.admin_deactivate_profile(
  p_target_user_id uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_role text;
  v_is_active boolean;
  v_active_admins bigint;
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN
    RAISE EXCEPTION 'Service role required' USING ERRCODE = '42501';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(74321091, 1);

  SELECT p.role, p.is_active
  INTO v_role, v_is_active
  FROM public.profiles AS p
  WHERE p.id = p_target_user_id
  FOR UPDATE;

  IF NOT FOUND OR NOT v_is_active THEN
    RAISE EXCEPTION 'Active user profile not found' USING ERRCODE = 'P0002';
  END IF;

  IF v_role = 'admin' THEN
    SELECT count(*)
    INTO v_active_admins
    FROM public.profiles AS p
    WHERE p.role = 'admin'
      AND p.is_active;

    IF v_active_admins <= 1 THEN
      RAISE EXCEPTION 'Cannot deactivate the last active admin'
        USING ERRCODE = '23514';
    END IF;
  END IF;

  UPDATE public.profiles
  SET is_active = false
  WHERE id = p_target_user_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_deactivate_profile(uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.admin_deactivate_profile(uuid) TO service_role;

-- Create a profile for each Auth account. Auth metadata can supply a display
-- name/username, but can never grant a privileged role.
CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_display_name text;
  v_username text;
  v_fallback_username text;
BEGIN
  v_display_name := left(
    coalesce(
      nullif(btrim(NEW.raw_user_meta_data ->> 'display_name'), ''),
      nullif(btrim(NEW.raw_user_meta_data ->> 'full_name'), ''),
      nullif(btrim(split_part(coalesce(NEW.email, ''), '@', 1)), ''),
      'Pengguna'
    ),
    100
  );

  v_username := lower(
    regexp_replace(
      coalesce(
        NEW.raw_user_meta_data ->> 'username',
        split_part(coalesce(NEW.email, ''), '@', 1),
        ''
      ),
      '[^a-zA-Z0-9_]',
      '_',
      'g'
    )
  );
  v_username := left(trim(both '_' FROM v_username), 32);
  IF char_length(v_username) < 3 THEN
    v_username := 'user';
  END IF;

  INSERT INTO public.profiles (id, display_name, username, role)
  VALUES (NEW.id, v_display_name, v_username, 'user')
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
EXCEPTION
  WHEN unique_violation THEN
    -- A duplicate requested username gets a deterministic, UUID-derived name.
    -- The suffix is server-generated, not taken from user metadata.
    v_fallback_username :=
      'u_' || left(replace(NEW.id::text, '-', ''), 30);
    INSERT INTO public.profiles (id, display_name, username, role)
    VALUES (NEW.id, v_display_name, v_fallback_username, 'user')
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.handle_new_auth_user()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
