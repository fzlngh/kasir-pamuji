-- Atomic checkout. Item input is a JSON array of objects with numeric
-- product_id and quantity fields. Duplicate product rows are consolidated.
-- Products are locked in ascending ID order to avoid checkout deadlocks.
DROP FUNCTION IF EXISTS public.checkout(jsonb);

CREATE OR REPLACE FUNCTION public.checkout(
  p_items jsonb,
  p_payment_method text,
  p_paid_amount bigint
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_user_id uuid;
  v_role text;
  v_item record;
  v_price bigint;
  v_stock integer;
  v_total numeric := 0;
  v_change numeric;
  v_sale_id bigint;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
  END IF;

  SELECT p.role
  INTO v_role
  FROM public.profiles AS p
  WHERE p.id = v_user_id
    AND p.is_active;

  IF v_role IS DISTINCT FROM 'kasir' THEN
    RAISE EXCEPTION 'Only cashier accounts may check out'
      USING ERRCODE = '42501';
  END IF;

  IF p_payment_method IS NULL OR p_payment_method NOT IN ('cash', 'qris', 'other') THEN
    RAISE EXCEPTION 'Unsupported payment method'
      USING ERRCODE = '22023';
  END IF;

  IF p_paid_amount IS NULL OR p_paid_amount < 0 THEN
    RAISE EXCEPTION 'Paid amount must be zero or greater'
      USING ERRCODE = '22023';
  END IF;

  IF p_items IS NULL OR jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Checkout requires between 1 and 100 item rows'
      USING ERRCODE = '22023';
  END IF;

  IF jsonb_array_length(p_items) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'Checkout requires between 1 and 100 item rows'
      USING ERRCODE = '22023';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) AS item(value)
    WHERE jsonb_typeof(item.value) IS DISTINCT FROM 'object'
       OR jsonb_typeof(item.value -> 'product_id') IS DISTINCT FROM 'number'
       OR jsonb_typeof(item.value -> 'quantity') IS DISTINCT FROM 'number'
       OR coalesce(item.value ->> 'product_id', '') !~ '^[1-9][0-9]{0,18}$'
       OR coalesce(item.value ->> 'quantity', '') !~ '^[1-9][0-9]{0,5}$'
       OR CASE
            WHEN coalesce(item.value ->> 'quantity', '') ~ '^[1-9][0-9]{0,5}$'
              THEN (item.value ->> 'quantity')::numeric > 100000
            ELSE false
          END
       OR CASE
            WHEN coalesce(item.value ->> 'product_id', '') ~ '^[1-9][0-9]{0,18}$'
              THEN (item.value ->> 'product_id')::numeric > 9223372036854775807
            ELSE false
          END
  ) THEN
    RAISE EXCEPTION 'Each checkout row must have a valid product_id and quantity'
      USING ERRCODE = '22023';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM (
      SELECT (item.value ->> 'product_id')::bigint AS product_id,
             sum((item.value ->> 'quantity')::integer) AS quantity
      FROM jsonb_array_elements(p_items) AS item(value)
      GROUP BY (item.value ->> 'product_id')::bigint
    ) AS requested
    WHERE requested.quantity > 100000
  ) THEN
    RAISE EXCEPTION 'Combined quantity for a product exceeds the limit'
      USING ERRCODE = '22023';
  END IF;

  -- Lock and validate all products before writing any sale data.
  FOR v_item IN
    SELECT (item.value ->> 'product_id')::bigint AS product_id,
           sum((item.value ->> 'quantity')::integer)::integer AS quantity
    FROM jsonb_array_elements(p_items) AS item(value)
    GROUP BY (item.value ->> 'product_id')::bigint
    ORDER BY (item.value ->> 'product_id')::bigint
  LOOP
    SELECT p.harga, p.stok
    INTO v_price, v_stock
    FROM public.products AS p
    WHERE p.id = v_item.product_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product % was not found', v_item.product_id
        USING ERRCODE = 'P0002';
    END IF;

    IF v_stock < v_item.quantity THEN
      RAISE EXCEPTION 'Insufficient stock for product %', v_item.product_id
        USING ERRCODE = '22000';
    END IF;

    v_total := v_total + (v_price::numeric * v_item.quantity::numeric);
  END LOOP;

  IF v_total > 9007199254740991 THEN
    RAISE EXCEPTION 'Sale total exceeds the supported amount'
      USING ERRCODE = '22003';
  END IF;
  IF p_paid_amount > 9007199254740991 THEN
    RAISE EXCEPTION 'Paid amount exceeds the supported amount'
      USING ERRCODE = '22003';
  END IF;

  IF p_payment_method = 'cash' AND p_paid_amount::numeric < v_total THEN
    RAISE EXCEPTION 'Cash received is less than the sale total'
      USING ERRCODE = '22023';
  END IF;
  IF p_payment_method <> 'cash' AND p_paid_amount::numeric <> v_total THEN
    RAISE EXCEPTION 'Non-cash payment must match the sale total'
      USING ERRCODE = '22023';
  END IF;

  v_change := p_paid_amount::numeric - v_total;
  INSERT INTO public.sales (
    cashier_id, total_amount, payment_method, paid_amount, change_amount
  )
  VALUES (
    v_user_id, v_total::bigint, p_payment_method, p_paid_amount, v_change::bigint
  )
  RETURNING id INTO v_sale_id;

  FOR v_item IN
    SELECT (item.value ->> 'product_id')::bigint AS product_id,
           sum((item.value ->> 'quantity')::integer)::integer AS quantity
    FROM jsonb_array_elements(p_items) AS item(value)
    GROUP BY (item.value ->> 'product_id')::bigint
    ORDER BY (item.value ->> 'product_id')::bigint
  LOOP
    INSERT INTO public.sale_items (
      sale_id, product_id, nama_produk, quantity, unit_price, line_total
    )
    SELECT v_sale_id,
           p.id,
           p.nama,
           v_item.quantity,
           p.harga,
           (p.harga::numeric * v_item.quantity::numeric)::bigint
    FROM public.products AS p
    WHERE p.id = v_item.product_id;

    UPDATE public.products AS p
    SET stok = p.stok - v_item.quantity,
        updated_at = now()
    WHERE p.id = v_item.product_id;
  END LOOP;

  RETURN v_sale_id;
END;
$function$;

